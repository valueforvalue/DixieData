// bake-release-notes -- Issue #585 slice 2.
//
// Parses CHANGELOG.md at the repo root and rewrites
// internal/releasehistory/baked.go with the populated `var baked []Entry`
// the binary ships with. The dev binary (no bake) keeps
// `var baked []Entry` as nil and the /about page renders an
// empty-state message.
//
// Usage:
//   go run ./scripts/bake-release-notes
//
// Wired into `make tpl` (Makefile) so every regeneration pass
// also refreshes the baked file. The release pipeline
// (scripts/release-github.ps1) invokes `make tpl` before
// tagging, so every shipped binary carries the release history
// matching its version.

package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"strings"

	"github.com/valueforvalue/DixieData/internal/releasehistory"
)

func main() {
	root, err := repoRoot()
	if err != nil {
		log.Fatalf("bake-release-notes: %v", err)
	}
	changelogPath := filepath.Join(root, "CHANGELOG.md")
	entries, err := releasehistory.ParseFile(changelogPath)
	if err != nil {
		log.Fatalf("bake-release-notes: parse %s: %v", changelogPath, err)
	}
	out := filepath.Join(root, "internal/releasehistory/baked.go")
	src, err := render(out, entries)
	if err != nil {
		log.Fatalf("bake-release-notes: render: %v", err)
	}
	if err := os.WriteFile(out, src, 0o644); err != nil {
		log.Fatalf("bake-release-notes: write %s: %v", out, err)
	}
	fmt.Printf("bake-release-notes: wrote %d release(s) to %s\n", len(entries), out)
}

func repoRoot() (string, error) {
	cwd, err := os.Getwd()
	if err != nil {
		return "", err
	}
	// Walk up to find CHANGELOG.md. The tool runs from any
	// working directory under the repo (most commonly the repo
	// root when invoked via `make`).
	dir := cwd
	for {
		if _, err := os.Stat(filepath.Join(dir, "CHANGELOG.md")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("could not find CHANGELOG.md walking up from %s", cwd)
		}
		dir = parent
	}
}

// render emits the Go source for baked.go. The output is
// gofmt-formatted so a `git diff` against the committed file is
// stable.
func render(path string, entries []releasehistory.Entry) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString(`// Code generated by scripts/bake-release-notes. DO NOT EDIT.
//
// Regenerated by ` + "`make tpl`" + ` before every release. The
// dev binary (no bake) keeps baked == nil; the /about page
// renders an empty-state message in that case. See
// docs/agents/notes/about-slice-1-research.md for the bake
// contract.

package releasehistory

var baked = []Entry{
`)
	for _, e := range entries {
		buf.WriteString("\t{\n")
		buf.WriteString(fmt.Sprintf("\t\tVersion: %q,\n", e.Version))
		if e.Codename != "" {
			buf.WriteString(fmt.Sprintf("\t\tCodename: %q,\n", e.Codename))
		}
		buf.WriteString(fmt.Sprintf("\t\tDate: %q,\n", e.Date))
		writeBullets(&buf, "Added", e.Added)
		writeBullets(&buf, "Changed", e.Changed)
		writeBullets(&buf, "Fixed", e.Fixed)
		writeBullets(&buf, "Removed", e.Removed)
		writeBullets(&buf, "Maintenance", e.Maintenance)
		writeBullets(&buf, "Documentation", e.Docs)
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		// Surface the unformatted source so the user can debug.
		os.Stderr.WriteString("--- unformatted source ---\n")
		os.Stderr.Write(buf.Bytes())
		os.Stderr.WriteString("--- end unformatted source ---\n")
		return nil, fmt.Errorf("gofmt: %w", err)
	}
	return formatted, nil
}

func writeBullets(buf *bytes.Buffer, field string, bullets []string) {
	if len(bullets) == 0 {
		return
	}
	buf.WriteString(fmt.Sprintf("\t\t%s: []string{\n", field))
	for _, b := range bullets {
		// Use %q so backslashes + quotes are escaped. Newlines
		// collapse to spaces; the parser never emits multi-line
		// bullets so this is defensive.
		single := strings.ReplaceAll(b, "\n", " ")
		buf.WriteString(fmt.Sprintf("\t\t\t%q,\n", single))
	}
	buf.WriteString("\t\t},\n")
}